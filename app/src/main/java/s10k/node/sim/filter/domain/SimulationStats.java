package s10k.node.sim.filter.domain;

/**
 * Simulation statistics.
 *
 * @param processed
 *        the number of datum processed, including generated datum
 * @param generated
 *        the number of datum generated by filters, scheduled tasks, controls,
 *        and stored instructions
 * @param output
 *        the number of datum that came out of the filters (and would be
 *        persisted or uploaded)
 * @param discarded
 *        the number of datum the filters discarded
 * @param durationMs
 *        the time spent processing datum, in milliseconds
 * @param polled
 *        the number of datum polled from datum sources
 * @author matt
 * @version 1.1
 */
public record SimulationStats(int processed, int generated, int output, int discarded, long durationMs,
		int polled) {

	/**
	 * Constructor, without polled datum.
	 *
	 * @param processed
	 *        the number of datum processed
	 * @param generated
	 *        the number of datum generated
	 * @param output
	 *        the number of datum that came out of the filters
	 * @param discarded
	 *        the number of datum the filters discarded
	 * @param durationMs
	 *        the time spent processing datum, in milliseconds
	 */
	public SimulationStats(int processed, int generated, int output, int discarded, long durationMs) {
		this(processed, generated, output, discarded, durationMs, 0);
	}

}
