package s10k.node.sim.filter.domain;

import org.jspecify.annotations.Nullable;
import com.fasterxml.jackson.annotation.JsonInclude;

/**
 * Where a processed datum came from.
 *
 * @param type
 *        the origin type
 * @param index
 *        for an input datum, its index in the request
 * @param parentSeq
 *        for a generated datum, the sequence number of the datum being
 *        processed when it was generated
 * @param stepId
 *        for a generated datum, the ID of the filter step that generated it, or
 *        {@code null} if not generated by a filter step
 * @param filterId
 *        for a generated datum, the {@code id} of the filter configuration that
 *        generated it, or {@code null} if not generated by a filter
 * @param controlId
 *        for a generated datum that a control published when a filter set its
 *        value, the control ID, or {@code null}
 * @param instruction
 *        for a datum published while the Instruction Execution Job ran an
 *        instruction, the {@link InstructionInfo#number()} of that instruction,
 *        or {@code null}
 * @param datumSourceId
 *        for a datum polled from a datum source, the {@code id} of the datum
 *        source configuration, or {@code null}
 * @author matt
 * @version 1.2
 */
@JsonInclude(JsonInclude.Include.NON_NULL)
public record DatumOrigin(Type type, @Nullable Integer index, @Nullable Integer parentSeq,
		@Nullable Integer stepId, @Nullable String filterId, @Nullable String controlId,
		@Nullable Integer instruction, @Nullable String datumSourceId) {

	/**
	 * Datum origin types.
	 */
	public enum Type {

		/** An input datum from the simulation request. */
		Input,

		/** A datum generated by a filter, by adding it to the Datum Queue. */
		Generated,

		/** A datum generated by a filter's scheduled task, between datum. */
		Scheduled,

		/**
		 * A datum published while the Instruction Execution Job ran a stored
		 * instruction, between datum.
		 */
		Instruction,

		/** A datum polled from a datum source, between datum. */
		Polled,

	}

	/**
	 * Create an input datum origin.
	 *
	 * @param index
	 *        the index of the datum in the request
	 * @return the origin
	 */
	public static DatumOrigin input(int index) {
		return new DatumOrigin(Type.Input, index, null, null, null, null, null, null);
	}

	/**
	 * Create a generated datum origin.
	 *
	 * @param parentSeq
	 *        the sequence number of the datum being processed, or {@code null}
	 *        if no datum was being processed
	 * @param stepId
	 *        the ID of the filter step that generated the datum, or
	 *        {@code null}
	 * @param filterId
	 *        the {@code id} of the filter configuration that generated the
	 *        datum, or {@code null}
	 * @return the origin
	 */
	public static DatumOrigin generated(@Nullable Integer parentSeq, @Nullable Integer stepId,
			@Nullable String filterId) {
		return new DatumOrigin(Type.Generated, null, parentSeq, stepId, filterId, null, null, null);
	}

	/**
	 * Create a scheduled task datum origin.
	 *
	 * @param filterId
	 *        the {@code id} of the filter whose task generated the datum, or
	 *        {@code null}
	 * @return the origin
	 */
	public static DatumOrigin scheduled(@Nullable String filterId) {
		return new DatumOrigin(Type.Scheduled, null, null, null, filterId, null, null, null);
	}

	/**
	 * Create an instruction run datum origin.
	 *
	 * @param instruction
	 *        the number of the instruction the job was running
	 * @param filterId
	 *        the {@code id} of the filter whose step issued the instruction, or
	 *        {@code null}
	 * @return the origin
	 */
	public static DatumOrigin instruction(int instruction, @Nullable String filterId) {
		return new DatumOrigin(Type.Instruction, null, null, null, filterId, null, instruction, null);
	}

	/**
	 * Create a polled datum origin.
	 *
	 * @param datumSourceId
	 *        the {@code id} of the datum source configuration
	 * @return the origin
	 */
	public static DatumOrigin polled(String datumSourceId) {
		return new DatumOrigin(Type.Polled, null, null, null, null, null, null, datumSourceId);
	}

	/**
	 * Get a copy of this origin for a datum a control published.
	 *
	 * @param controlId
	 *        the control ID
	 * @return the new origin
	 */
	public DatumOrigin withControlId(@Nullable String controlId) {
		return new DatumOrigin(type, index, parentSeq, stepId, filterId, controlId, instruction,
				datumSourceId);
	}

}
